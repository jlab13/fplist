#!/usr/bin/env python3
"""Validate machine translations and build gndtui's overlay .ts file.

Reads OUTDIR/items.json and every OUTDIR/batch_NNN.out.jsonl, checks each
translation against the mechanical PX4 translation rules and writes a Qt
Linguist .ts file containing one context per record key (the same layout as
PX4-Metadata-Translations), each message tagged as machine-translated.

usage: collect.py OUTDIR OUT_TS --lang uk [--model NAME] [--report FILE]
Exit status 1 if any batch is missing or any translation fails a check
(failed ones are left out of the .ts and listed in the report).
"""
import argparse
import glob
import json
import os
import re
import sys
from xml.sax.saxutils import escape

IDENT = re.compile(r"\b[A-Za-z0-9]*_[A-Za-z0-9_]*[A-Za-z0-9]\b")
PLACEHOLDER = re.compile(r"\{\d+(?::[^}]*)?\}")
TAG = re.compile(r"</?[a-zA-Z][^>]*>")
CODE = re.compile(r"```.*?```|`[^`\n]+`", re.S)
URL = re.compile(r"https?://[^\s,;)\]]*[^\s,;.)\]]")  # without trailing punctuation
NUMBER = re.compile(r"(?<![\w.])\d+(?:\.\d+)?(?![\w])")
LATIN_WORDS = re.compile(r"[A-Za-z]{4,}")
ENGLISH_WORDS = re.compile(r"\b(the|to|of|and|is|for|when|with|be|if|this|will|that|are)\b", re.I)


def check(src, tr):
    """List of rule violations (empty = OK)."""
    errs = []
    if not tr.strip():
        return ["empty"]
    if src.count("\n") != tr.count("\n"):
        errs.append(f"line breaks {tr.count(chr(10))} != {src.count(chr(10))}")
    for name, rx in (("identifier", IDENT), ("placeholder", PLACEHOLDER), ("tag", TAG), ("code", CODE),
                     ("url", URL)):
        for tok in set(rx.findall(src)):
            if tok not in tr:
                errs.append(f"{name} changed/missing: {tok[:40]}")
    for num in set(NUMBER.findall(src)):
        if "." in num and num.replace(".", ",") in tr and num not in tr:
            errs.append(f"decimal comma: {num}")
    # untranslated: an English sentence copied verbatim (product/model name
    # lists like "Pixhawk/Pixracer" legitimately stay as they are)
    if tr.strip() == src.strip() and len(LATIN_WORDS.findall(src)) > 3 and ENGLISH_WORDS.search(src):
        errs.append("not translated")
    if re.search(r"[ыэъё]", tr, re.I):
        errs.append("Russian letters")
    return errs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("outdir")
    ap.add_argument("out_ts")
    ap.add_argument("--lang", default="uk")
    ap.add_argument("--model", default="claude-sonnet")
    ap.add_argument("--report", default=None)
    a = ap.parse_args()

    items = {it["id"]: it for it in json.load(open(os.path.join(a.outdir, "items.json")))}
    got, problems, missing_batches = {}, [], []
    for bf in sorted(glob.glob(os.path.join(a.outdir, "batch_[0-9][0-9][0-9].jsonl"))):
        want = [json.loads(l)["id"] for l in open(bf) if l.strip()]
        of = bf[:-6] + ".out.jsonl"
        if not os.path.exists(of):
            missing_batches.append(os.path.basename(bf))
            continue
        seen = set()
        for n, line in enumerate(open(of), 1):
            if not line.strip():
                continue
            try:
                rec = json.loads(line)
                iid, text = rec["id"], rec["text"]
            except (ValueError, KeyError) as e:
                problems.append((os.path.basename(of), f"line {n}: bad JSON ({e})", ""))
                continue
            if iid not in items:
                problems.append((os.path.basename(of), f"unknown id {iid}", ""))
                continue
            seen.add(iid)
            errs = check(items[iid]["text"], text)
            if errs:
                problems.append((os.path.basename(of), f"id {iid}: " + "; ".join(errs), items[iid]["text"][:80]))
            else:
                got[iid] = text
        for iid in want:
            if iid not in seen:
                problems.append((os.path.basename(of), f"id {iid}: missing", items[iid]["text"][:80]))

    records = 0
    with open(a.out_ts, "w") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n<!DOCTYPE TS>\n')
        f.write(f'<TS version="2.1" language="{a.lang}" sourcelanguage="en">\n')
        f.write(f"  <!-- Machine translation ({a.model}) following the PX4 translation guide and\n"
                "       term sheet; NOT reviewed. Generated by tools/px4-translate. -->\n")
        for iid in sorted(got):
            it = items[iid]
            for key in it["keys"]:
                records += 1
                f.write("  <context>\n")
                f.write(f"    <name>{escape(key)}</name>\n")
                f.write("    <message>\n")
                f.write(f"      <source>{escape(it['text'])}</source>\n")
                f.write(f"      <translation>{escape(got[iid])}</translation>\n")
                f.write(f"      <extracomment>machine-translated: {escape(a.model)}</extracomment>\n")
                f.write("    </message>\n")
                f.write("  </context>\n")
        f.write("</TS>\n")

    lines = [f"translated {len(got)}/{len(items)} unique strings -> {records} records in {a.out_ts}",
             f"missing batches: {', '.join(missing_batches) or 'none'}",
             f"problems: {len(problems)}"]
    lines += [f"  {b}: {msg}" + (f"  [{src}]" if src else "") for b, msg, src in problems]
    text = "\n".join(lines)
    print(text)
    if a.report:
        open(a.report, "w").write(text + "\n")
    return 1 if (problems or missing_batches) else 0


if __name__ == "__main__":
    sys.exit(main())
